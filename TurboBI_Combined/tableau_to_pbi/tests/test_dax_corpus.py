@pytest.mark.parametrize(
    "test_id,formula,table,ftp,prefs,mrefs,expected",
    CASES,
    ids=[c[0] for c in CASES],
)
def test_translator(test_id, formula, table, ftp, prefs, mrefs, expected):
    """Pinned behavior — translator output must match the captured value.

    ``expected=None`` means we're asserting the translator rejects this
    construct. Once a new rule lands that DOES translate it, regenerate
    this file and the test for the previously-unsupported case will flip
    from None to the new DAX string.
    """
    actual = translate_tableau_to_dax(
        formula, table, {}, [],
        field_to_pbi=ftp,
        parameter_refs=prefs,
        measure_refs=mrefs,
    )
    assert actual == expected
